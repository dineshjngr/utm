import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { blogPosts } from '../src/data/blog-posts.js';

const root = join(import.meta.dirname, '..');
const landingPages = join(root, 'landing-pages');
const routes = [];

function collectRoutes(directory, prefix = '') {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const route = `${prefix}${entry.name}`;
    const nested = join(directory, entry.name);
    if (readdirSync(nested).includes('index.html')) routes.push(route);
    collectRoutes(nested, `${route}/`);
  }
}

collectRoutes(landingPages);

const redirects = [
  '# Generated by scripts/generate-redirects.js. Canonical public routes are served from the site root.',
  '/about.html /about/ 301',
  '/contact.html /contact/ 301',
  '/blog/posts/ /blog/ 301',
  '/blog/posts/index.html /blog/ 301',
];

for (const route of routes.sort()) {
  redirects.push(`/landing-pages/${route} /${route}/ 301`);
  redirects.push(`/landing-pages/${route}/ /${route}/ 301`);
  redirects.push(`/landing-pages/${route}/index.html /${route}/ 301`);
}

for (const { slug } of blogPosts) {
  redirects.push(`/blog/${slug} /${slug}/ 301`);
  redirects.push(`/blog/${slug}/ /${slug}/ 301`);
  redirects.push(`/blog/${slug}/index.html /${slug}/ 301`);
  redirects.push(`/blog/posts/${slug}.html /${slug}/ 301`);
}

writeFileSync(join(root, 'public', '_redirects'), `${redirects.join('\n')}\n`);
console.log(`Generated ${redirects.length - 1} canonical redirects.`);
